export type Translate = (
  key: TranslationKey,
  values?: Record<string, string | number>,
) => string;

function initialLocale(): Locale {
  // 语言选择要跨刷新保留：财务同事切成英文后刷新又变回中文是当 bug 报的。
  const stored = window.localStorage.getItem(LOCALE_STORAGE_KEY);
  return stored === "en-US" || stored === "zh-CN" ? stored : "zh-CN";
}

export function useI18n() {
  const [locale, setLocale] = useState<Locale>(initialLocale);

  useEffect(() => {
    window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
    // 让 :lang() 选择器和屏幕阅读器都拿到正确的语言。
    document.documentElement.lang = locale;
  }, [locale]);

  const t = useCallback<Translate>(
    (key, values) => {
      let message: string = resources[locale][key];
      for (const [name, value] of Object.entries(values ?? {})) {
        // 同一个占位符可能出现多次（例如 {count}），逐个全局替换。
        message = message.replaceAll(`{${name}}`, String(value));
      }
      return message;
    },
    [locale],
  );

  return useMemo(
    () => ({
      locale,
      t,
      toggleLocale: () =>
        setLocale((current) => (current === "zh-CN" ? "en-US" : "zh-CN")),
    }),
    [locale, t],
  );
}
